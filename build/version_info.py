"""Windows version resource for the packaged executables.

The version numbers here are the single source of truth for what Windows
shows in the file properties dialog and what the EXE reports as its file
version. ``pybmap.__version__`` is kept in step by ``scripts/check_version.py``
and by a test, so a release cannot ship a mismatched pair.
"""

from __future__ import annotations

import os
import sys

#: Keep in sync with ``pyproject.toml`` and ``pybmap.__version__``.
VERSION = "1.0.0.0"
VERSION_TUPLE = tuple(int(part) for part in VERSION.split("."))

COMPANY = "bosectl-win contributors"
PRODUCT = "BoseCtl for Windows"
DESCRIPTION = "Local control for Bose headphones over the BMAP protocol"
COPYRIGHT = "MIT licensed. BMAP implementation derived from aaronsb/bosectl."
INTERNAL_NAME = "BoseCtl"
ORIGINAL_FILENAME = "BoseCtl.exe"


def _vs_version_info(original_filename=ORIGINAL_FILENAME, internal_name=INTERNAL_NAME):
    """Build the PyInstaller ``VSVersionInfo`` structure."""
    from PyInstaller.utils.win32.versioninfo import (
        FixedFileInfo, StringFileInfo, StringStruct, StringTable,
        VarFileInfo, VarStruct, VSVersionInfo,
    )

    return VSVersionInfo(
        ffi=FixedFileInfo(
            filevers=VERSION_TUPLE,
            prodvers=VERSION_TUPLE,
            mask=0x3F,
            flags=0x0,
            OS=0x40004,            # VOS_NT_WINDOWS32
            fileType=0x1,          # VFT_APP
            subtype=0x0,
            date=(0, 0),
        ),
        kids=[
            StringFileInfo([
                StringTable("040904B0", [
                    StringStruct("CompanyName", COMPANY),
                    StringStruct("FileDescription", DESCRIPTION),
                    StringStruct("FileVersion", VERSION),
                    StringStruct("InternalName", internal_name),
                    StringStruct("LegalCopyright", COPYRIGHT),
                    StringStruct("OriginalFilename", original_filename),
                    StringStruct("ProductName", PRODUCT),
                    StringStruct("ProductVersion", VERSION),
                ]),
            ]),
            VarFileInfo([VarStruct("Translation", [0x0409, 1200])]),
        ],
    )


def write(target, original_filename=ORIGINAL_FILENAME, internal_name=INTERNAL_NAME):
    """Serialise the version resource next to the spec file."""
    info = _vs_version_info(original_filename, internal_name)
    with open(target, "w", encoding="utf-8") as handle:
        handle.write("# Generated by build/version_info.py - do not edit.\n")
        handle.write("VSVersionInfo(\n")
        handle.write("    ffi=FixedFileInfo(%r, %r, 0x3F, 0x0, 0x40004, 0x1, 0x0, (0, 0)),\n"
                     % (VERSION_TUPLE, VERSION_TUPLE))
        handle.write("    kids=[StringFileInfo([StringTable('040904B0', [\n")
        for key, value in (
            ("CompanyName", COMPANY),
            ("FileDescription", DESCRIPTION),
            ("FileVersion", VERSION),
            ("InternalName", internal_name),
            ("LegalCopyright", COPYRIGHT),
            ("OriginalFilename", original_filename),
            ("ProductName", PRODUCT),
            ("ProductVersion", VERSION),
        ):
            handle.write("        StringStruct(%r, %r),\n" % (key, value))
        handle.write("    ])]), VarFileInfo([VarStruct('Translation', [0x0409, 1200])])],\n")
        handle.write(")\n")
    return target


if __name__ == "__main__":  # pragma: no cover - build helper
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "version_info.txt")
    print("wrote", write(out))
